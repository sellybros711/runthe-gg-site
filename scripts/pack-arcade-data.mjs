#!/usr/bin/env node
/* PACK THE ARCADE'S GENERATED DATASETS IN PLACE.
 *
 * The four files below are written by scrapers that run on a schedule, and
 * each one is loaded by between two and nine arcade pages as a blocking
 * script. Packing is explained in scripts/lib/packdata.mjs; the short version
 * is that writing every field name and every team name once instead of once
 * per player takes former.js from 1225 KB to 467 KB, and takes the parse it
 * costs a phone from about 170 ms to about 40 ms.
 *
 * This is idempotent and shape-preserving: it reads whatever is on disk
 * (packed or not) the way a browser would, and writes the packed form of the
 * same values. Running it twice changes nothing the second time, which is what
 * lets the scrapers call it unconditionally.
 *
 *   node scripts/pack-arcade-data.mjs              pack all four
 *   node scripts/pack-arcade-data.mjs former       just that one
 *   node scripts/pack-arcade-data.mjs --check      pack nothing, report sizes
 *
 * Each scraper calls it for its own file after writing it, so the daily
 * refreshes keep shipping the packed form. Nothing else needs to know: the
 * decoder rides inside the generated file and the global it defines is
 * unchanged, so data.js, the games and check-colleges.mjs all read exactly
 * what they read before.
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { packFile, loadGlobal } from './lib/packdata.mjs';

/* One entry per generated file. `meta` pulls the top-level fields the file
   exposes alongside its rows, so a consumer reading `.updated` or `.count`
   still finds them. */
const FILES = {
  former: {
    path: 'arcade/former.js',
    global: 'RTG_FORMER',
    key: 'players',
    banner: 'GENERATED by scripts/fetch-former.mjs. Do not edit. Recognizable former\nplayers (high draft pick OR >=2 notable seasons) for the arcade games.\nPacked by scripts/pack-arcade-data.mjs: see scripts/lib/packdata.mjs.',
    rows: (G) => G.players,
    meta: (G) => ({ updated: G.updated, count: G.players.length })
  },
  rosters: {
    path: 'arcade/rosters.js',
    global: 'RTG_ROSTERS',
    key: 'players',
    banner: 'GENERATED by scripts/fetch-rosters.mjs. Do not edit. Current rosters.\nPacked by scripts/pack-arcade-data.mjs: see scripts/lib/packdata.mjs.',
    rows: (G) => G.players,
    meta: (G) => ({ updated: G.updated, count: G.players.length }),
    extra: (G) => (G.divisions ? { divisions: G.divisions } : {})
  },
  jerseys: {
    path: 'arcade/jerseys.js',
    global: 'RTG_JERSEYS',
    key: 'stints',
    banner: 'GENERATED by scripts/fetch-jerseys.mjs. Do not edit. Jersey stints.\nPacked by scripts/pack-arcade-data.mjs: see scripts/lib/packdata.mjs.',
    rows: (G) => G.stints,
    meta: (G) => ({ updated: G.updated, count: G.stints.length })
  },
  awards: {
    path: 'arcade/awards.js',
    global: 'RTG_AWARDS',
    key: 'players',
    /* A lookup, not a list: keyed "SPORT|normalised name". The key rides as a
       field through the packer and the decoder puts it back as the key. */
    banner: 'GENERATED by scripts/fetch-awards.mjs. Do not edit. Elite awards.\nPacked by scripts/pack-arcade-data.mjs: see scripts/lib/packdata.mjs.',
    mapKey: '__k',
    rows: (G) => Object.keys(G.players).map((k) => ({ __k: k, ...G.players[k] })),
    meta: (G) => ({ updated: G.updated, count: G.count }),
    extra: (G) => (G.bySport ? { bySport: G.bySport } : {})
  }
};

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const want = args.filter((a) => !a.startsWith('--'));
const names = want.length ? want : Object.keys(FILES);

for (const n of names) {
  const spec = FILES[n];
  if (!spec) {
    console.error(`unknown dataset "${n}". Known: ${Object.keys(FILES).join(', ')}`);
    process.exit(2);
  }
}

const kb = (n) => Math.round(n / 1024);
let moved = 0;

for (const name of names) {
  const spec = FILES[name];
  const before = readFileSync(spec.path, 'utf8');
  const G = loadGlobal(before, spec.global);
  if (!G) { console.error(`${spec.path}: does not define window.${spec.global}`); process.exit(1); }

  const rows = spec.rows(G);
  const out = packFile({
    global: spec.global,
    key: spec.key,
    rows,
    meta: spec.meta(G),
    extra: spec.extra ? spec.extra(G) : {},
    mapKey: spec.mapKey || null,
    banner: spec.banner
  });

  /* NEVER WRITE A FILE THAT DOES NOT READ BACK. These load on every arcade
     page ahead of the game, so a packed file that decodes to something else is
     not a smaller download, it is a broken site. Compare the values, not the
     text: key order changes and is not a difference anybody can observe. */
  const back = loadGlobal(out, spec.global);
  const backRows = spec.mapKey
    ? Object.keys(back[spec.key]).map((k) => ({ [spec.mapKey]: k, ...back[spec.key][k] }))
    : back[spec.key];
  const norm = (o) => JSON.stringify(Object.keys(o).sort().map((k) => [k, o[k] === undefined ? null : o[k]]));
  if (backRows.length !== rows.length) {
    console.error(`${spec.path}: packed to ${backRows.length} rows, had ${rows.length}`);
    process.exit(1);
  }
  for (let i = 0; i < rows.length; i++) {
    if (norm(rows[i]) !== norm(backRows[i])) {
      console.error(`${spec.path}: row ${i} does not survive the roundtrip`);
      console.error('  was  ' + JSON.stringify(rows[i]));
      console.error('  back ' + JSON.stringify(backRows[i]));
      process.exit(1);
    }
  }

  const rawBefore = statSync(spec.path).size;
  const gzBefore = gzipSync(Buffer.from(before), { level: 6 }).length;
  const gzAfter = gzipSync(Buffer.from(out), { level: 6 }).length;
  const same = out === before;

  console.log(
    spec.path.padEnd(26) +
    (same
      ? `already packed  ${kb(rawBefore)} KB raw / ${kb(gzBefore)} KB wire`
      : `${kb(rawBefore)} -> ${kb(out.length)} KB raw   ${kb(gzBefore)} -> ${kb(gzAfter)} KB wire   ${rows.length} rows`));

  if (!checkOnly && !same) { writeFileSync(spec.path, out); moved++; }
}

if (checkOnly) console.log('\n--check: nothing written');
else if (moved) console.log(`\npacked ${moved} file${moved === 1 ? '' : 's'}. Bump their cache versions: node scripts/bump-cachebust.mjs <file>`);
else console.log('\nnothing to do');
