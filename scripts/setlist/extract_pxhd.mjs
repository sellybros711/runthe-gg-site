/* PXHD for Segue, lifted out of Run The Tour rather than rewritten.
 *
 *   node scripts/setlist/extract_pxhd.mjs          write setlist/pxhd.js
 *   node scripts/setlist/extract_pxhd.mjs --check  fail if setlist/pxhd.js has drifted
 *
 * The concert is drawn in the putt putt world's style, and that style IS this renderer: one light from
 * the top left, five step hue shifted ramps, contact shadows, and the soft outline one pixel inside a
 * shape in its own shadow colour. A second hand written copy would agree with golf for exactly as long
 * as nobody touched either, so this file is generated from golf/index.html and check_data.mjs runs the
 * --check arm. Re-run it after any change to PXHD in golf.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'golf/index.html', OUT = 'setlist/pxhd.js';
const START = 'var PXHD=(function(){';
const RET = 'return { render, renderMap, ramp, mix, Sprite, skinRamp, hairRamp, lum };';

export function extract(){
  const s = readFileSync(SRC, 'utf8');
  const a = s.indexOf(START);
  const r = a < 0 ? -1 : s.indexOf(RET, a);
  const e = r < 0 ? -1 : s.indexOf('})();', r);
  if (a < 0 || r < 0 || e < 0) throw new Error('PXHD not found in ' + SRC);
  const body = s.slice(a, e + 5);
  return `/* GENERATED by scripts/setlist/extract_pxhd.mjs from ${SRC}. Do not hand edit.
   Run The Tour's PXHD renderer, so Segue's stage is lit and outlined exactly the way the putt putt
   world is. Re-run the extractor after any change to PXHD in golf, or this copy drifts behind it. */
${body}
export default PXHD;
`;
}

if (process.argv[1] && process.argv[1].endsWith('extract_pxhd.mjs')){
  const want = extract();
  if (process.argv.includes('--check')){
    const have = readFileSync(OUT, 'utf8');
    if (have !== want){ console.error(OUT + ' has drifted from ' + SRC + '. Run node scripts/setlist/extract_pxhd.mjs'); process.exit(1); }
    console.log(OUT + ' matches ' + SRC);
  } else { writeFileSync(OUT, want); console.log('wrote ' + OUT + ' (' + want.length + ' bytes)'); }
}
