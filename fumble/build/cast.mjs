#!/usr/bin/env node
/* Lift the MythiBall cast into Fumble.

     node fumble/build/cast.mjs [path/to/mythiball/index.html]

   Writes fumble/cast.js: every MythiBall character (name, role, ratings, its
   palette and the poses Fumble draws), the seventeen clubs and their parks.

   THE SOURCE IS READ, NEVER COPIED BY HAND. MythiBall is one self contained
   page, so its tables are object literals inside a script. They are found by
   their declarations and brace matched, and the sprite table is parsed as
   JSON because that is what the MythiBall builder writes. A hand copy would
   be a second cast that drifts the first time somebody redraws a character.

   ONLY THE POSES FUMBLE DRAWS ARE KEPT. The full table is about 1.1MB; a
   football game has no use for a batting stance, a swing or a windup. A pose
   in MythiBall may be a reference ('@back') to another pose. A reference to a
   pose that is kept stays a reference; a reference to one that is dropped is
   resolved to that pose's pixels, or it would point at nothing. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] || path.join(here, '..', '..', 'mythiball', 'index.html');
if (!fs.existsSync(src)) {
  console.error('No MythiBall page at ' + src + '. Pass its path as the first argument.');
  process.exit(1);
}
const html = fs.readFileSync(src, 'utf8');

/* The balanced literal that follows `decl`. Strings are skipped, so a brace
   inside a character's note cannot end the walk early. */
function literal(decl) {
  const at = html.indexOf(decl);
  if (at < 0) throw new Error('not found: ' + decl);
  let i = at + decl.length;
  while (html[i] !== '{' && html[i] !== '[') i++;
  const open = html[i], close = open === '{' ? '}' : ']';
  let depth = 0, q = null;
  for (let j = i; j < html.length; j++) {
    const c = html[j];
    if (q) { if (c === '\\') { j++; continue; } if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === '`') { q = c; continue; }
    if (c === '/' && html[j + 1] === '*') { j = html.indexOf('*/', j + 2) + 1; continue; }
    if (c === '/' && html[j + 1] === '/') { j = html.indexOf('\n', j); continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return html.slice(i, j + 1);
  }
  throw new Error('unbalanced: ' + decl);
}
const evalLiteral = s => Function('"use strict";return (' + s + ')')();

const SPRITES = JSON.parse(literal('const V2_SPRITES = '));
const ROSTER = evalLiteral(literal('const ROSTER = '));
const CLUBS = evalLiteral(literal('const OPPONENTS = '));
const PARKS = evalLiteral(literal('const STADIUM_THEMES = '));
/* Five clubs have no park of their own and MythiBall plays them in this one. */
PARKS._default = evalLiteral(literal('const DEFAULT_THEME = '));

const POSES = ['idle', 'run1', 'run2', 'run3', 'run4', 'cheer', 'slump', 'catch', 'throw', 'release'];

function resolve(f, pose) {
  let raw = f[pose];
  for (let n = 0; n < 4 && typeof raw === 'string' && raw.charCodeAt(0) === 64; n++) raw = f[raw.slice(1)];
  return raw;
}

const chars = {};
for (const r of ROSTER) {
  const spr = SPRITES[r.k];
  if (!spr) throw new Error('no sprite for ' + r.k);
  const f = {};
  for (const pose of POSES) {
    let raw = spr.f[pose];
    if (raw == null) raw = '@idle';
    if (typeof raw === 'string' && raw.charCodeAt(0) === 64) {
      const target = raw.slice(1);
      raw = POSES.includes(target) && spr.f[target] != null ? raw : resolve(spr.f, target) ?? resolve(spr.f, 'idle');
    }
    f[pose] = raw;
  }
  /* A reference to a pose that itself became a reference is flattened one
     step, so the page never has to walk more than one hop. */
  for (const pose of POSES) {
    const v = f[pose];
    if (typeof v === 'string' && v.charCodeAt(0) === 64) {
      const t = f[v.slice(1)];
      if (typeof t === 'string' && t.charCodeAt(0) === 64) f[pose] = t;
    }
  }
  chars[r.k] = { n: r.n, role: r.role, pow: r.pow, spd: r.spd, con: r.con, def: r.def, p: spr.p, f };
}

/* A club fields its first seven that exist in the cast. */
const clubs = CLUBS.map(c => ({ name: c.name, color: c.color, roster: c.roster.filter(k => chars[k]) }));
for (const c of clubs) if (c.roster.length < 7) throw new Error(c.name + ' has fewer than seven characters');

const parks = {};
for (const [name, t] of Object.entries(PARKS)) {
  parks[name] = { park: t.park, sky: t.sky, wall: t.wall, wallLine: t.wallLine, marker: t.marker,
    track: t.track, grass: t.grass, crowd: t.crowd, night: !!t.night, snow: !!t.snow };
}

const out = '/* GENERATED by fumble/build/cast.mjs from mythiball/index.html. Do not edit by hand. */\n' +
  'window.FUMBLE_CAST=' + JSON.stringify({ w: 64, h: 64, chars, clubs, parks }) + ';\n';
const dest = path.join(here, '..', 'cast.js');
fs.writeFileSync(dest, out);
console.log('wrote ' + path.relative(process.cwd(), dest) + ': ' + Object.keys(chars).length + ' characters, ' +
  clubs.length + ' clubs, ' + Object.keys(parks).length + ' parks, ' + (out.length / 1024).toFixed(0) + 'KB');
