/* Stage 6, the brand mark.
 *
 *   node cfb/build/06-mark.mjs
 *
 * Generates the CFB puzzle-helmet mark as three SVGs under cfb/brand/. Written as a generator rather than hand-authored
   paths because the knob geometry is four arcs whose sweep flags all depend on which way
   round the piece is traced, and getting one wrong is invisible until it renders inside
   out. Change CX/CY/R here and every seam stays consistent. Run from the repo root. */
import { writeFileSync } from 'fs';

const CX = 26, CY = 32, R = 22;   // helmet shell, sat left of centre to leave room for the cage
const D = 11.5, K = 3.9;          // knob centre distance along a seam, and knob radius
const f = (n) => Math.round(n * 100) / 100;

const N = [CX, CY - R], E = [CX + R, CY], S = [CX, CY + R], W = [CX - R, CY];
const up = (t) => [CX, f(CY - t)], dn = (t) => [CX, f(CY + t)];
const lf = (t) => [f(CX - t), CY], rt = (t) => [f(CX + t), CY];
const P = (p) => p[0] + ' ' + p[1];

/* A seam runs from the centre out to a rim point, or back. The knob bulges to one side;
   which side alternates around the mark, so the four pieces interlock like a pinwheel. */
const arc = (a, b, sweep) => 'A' + K + ' ' + K + ' 0 0 ' + sweep + ' ' + P(b);
const rim = (to, sweep) => 'A' + R + ' ' + R + ' 0 0 ' + sweep + ' ' + P(to);

const PIECES = [
  { /* top left  */ fill: '#10b981',
    d: 'M' + P([CX, CY]) + ' L' + P(lf(D - K)) + ' ' + arc(lf(D - K), lf(D + K), 0) +
       ' L' + P(W) + ' ' + rim(N, 1) +
       ' L' + P(up(D + K)) + ' ' + arc(up(D + K), up(D - K), 1) + ' Z' },
  { /* top right */ fill: '#fbbf24',
    d: 'M' + P([CX, CY]) + ' L' + P(up(D - K)) + ' ' + arc(up(D - K), up(D + K), 0) +
       ' L' + P(N) + ' ' + rim(E, 1) +
       ' L' + P(rt(D + K)) + ' ' + arc(rt(D + K), rt(D - K), 1) + ' Z' },
  { /* bot right */ fill: '#d97706',
    d: 'M' + P([CX, CY]) + ' L' + P(rt(D - K)) + ' ' + arc(rt(D - K), rt(D + K), 0) +
       ' L' + P(E) + ' ' + rim(S, 1) +
       ' L' + P(dn(D + K)) + ' ' + arc(dn(D + K), dn(D - K), 1) + ' Z' },
  { /* bot left  */ fill: '#047857',
    d: 'M' + P([CX, CY]) + ' L' + P(dn(D - K)) + ' ' + arc(dn(D - K), dn(D + K), 0) +
       ' L' + P(S) + ' ' + rim(W, 1) +
       ' L' + P(lf(D + K)) + ' ' + arc(lf(D + K), lf(D - K), 1) + ' Z' },
];

/* THE CAGE HANGS OFF THE RIGHT EDGE, which is the whole reason the shell sits left of
   centre. Drawn dark first and light on top, so it reads as a cage against the gold and
   amber quarters it crosses rather than dissolving into them. */
const CAGE = [
  /* the hoop: taller than it is wide, and its left side rides the shell's own edge */
  { w: 2.1, d: 'M47.5 27 Q57.5 28.5 59.4 37.5 Q60.6 47.5 52.5 54 Q45.5 56.6 43.2 48 Q41.8 36.5 47.5 27 Z' },
  /* one bar down and two across, which is what turns a hoop into a cage */
  { w: 1.8, d: 'M50.8 27.4 Q53.4 41.4 50.8 54.6' },
  { w: 1.8, d: 'M43.4 37 Q51.4 36 59.2 37.6' },
  { w: 1.8, d: 'M42.9 46 Q51 45.2 58.6 46.8' },
];

const shell = PIECES.map((p) =>
  '    <path fill="' + p.fill + '" d="' + p.d + '"/>').join('\n');
const cage = (stroke, bump) => CAGE.map((c) =>
  '    <path stroke="' + stroke + '" stroke-width="' + f(c.w + bump) + '" d="' + c.d + '"/>').join('\n');

const ART =
'  <g stroke="#f8fafc" stroke-width="2" stroke-linejoin="round" stroke-linecap="round">\n' +
shell + '\n  </g>\n' +
'  <g fill="none" stroke-linecap="round" stroke-linejoin="round">\n' +
cage('#0f172a', 1.4) + '\n' +
cage('#e2e8f0', 0) + '\n  </g>';

/* The bare mark is cropped to its own ink, so it drops into the header at the header's
   aspect instead of arriving in a square box with air down both sides. The two plated
   icons stay square, because a plate is the thing that makes them square. */
const HEAD = (label, box) =>
'<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + (box || '0 0 64 64') + '" role="img"\n' +
'     aria-label="College Football: Perfect Season">\n' +
'  <title>College Football: Perfect Season</title>\n' + label + '\n';

const NOTE_MARK = `  <!--
    THE BARE MARK. Use this wherever there is already a surface behind it.

    It is the RunThe.GG puzzle helmet, the family mark, in this game's colorway: green
    and gold rather than four unrelated hues, because that is what a school looks like.
    The four quarters still run emerald, gold, amber, deep green so the mark keeps four
    tellable pieces at 32px instead of flattening into one disc.

    NO TYPE IN THE MARK, so it draws at 16px in a browser tab with no font loaded.

    GENERATED by cfb/build/06-mark.mjs. Edit that, not this.
  -->`;

const NOTE_ICON = `  <!--
    THE MARK ON ITS OWN PLATE, for anything that wants a square: the favicon, a browser
    tab, a bookmark, a home screen. #111827 is the panel the game draws every card on.

    ONE PICTURE AT EVERY SIZE, including 16, where the cage goes to a few grey pixels and
    reads as texture rather than as a facemask. That is a real cost and it buys one mark
    instead of two: at 32, which is what a retina tab actually draws, the cage reads.

    GENERATED by cfb/build/06-mark.mjs. Edit that, not this.
  -->`;

const NOTE_MASK = `  <!--
    THE MASKABLE ICON, WHICH IS A DIFFERENT DRAWING AND NOT icon.svg SCALED.

    Android crops a maskable icon to whatever shape the launcher feels like and only
    guarantees the middle 80%, a circle of radius 0.4 of the width. So the plate runs full
    bleed with no corners of its own, because the launcher supplies the corners, and the
    mark is pulled in to sit inside that circle. Handing a launcher icon.svg would crop
    its corners and the outer edge of the cage, and the cage is what has to survive.

    GENERATED by cfb/build/06-mark.mjs. Edit that, not this.
  -->`;

writeFileSync('cfb/brand/mark.svg', HEAD(NOTE_MARK, '3 7 59 53') + ART + '\n</svg>\n');
writeFileSync('cfb/brand/icon.svg', HEAD(NOTE_ICON) +
  '  <rect width="64" height="64" rx="14" fill="#111827"/>\n' +
  '  <g transform="translate(32 32) scale(0.86) translate(-32 -32)">\n' +
  ART.replace(/^/gm, '  ') + '\n  </g>\n</svg>\n');
writeFileSync('cfb/brand/icon-maskable.svg', HEAD(NOTE_MASK) +
  '  <rect width="64" height="64" fill="#111827"/>\n' +
  '  <g transform="translate(32 32) scale(0.62) translate(-32 -32)">\n' +
  ART.replace(/^/gm, '  ') + '\n  </g>\n</svg>\n');
console.log('wrote mark.svg, icon.svg, icon-maskable.svg');
