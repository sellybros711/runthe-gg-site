#!/usr/bin/env node
/* Write functions/_stumpire/pages.js from web/play.html and web/admin.html.
 * The shells are served by a Pages Function rather than as static files, so
 * nobody the gate refuses can fetch them by another URL. Edit the HTML, then:
 *
 *   node functions/_stumpire/build/pages.mjs
 *
 * test/pages.test.mjs fails if pages.js and the HTML have drifted. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
export function render() {
  const play = fs.readFileSync(path.join(HERE, '../web/play.html'), 'utf8');
  const admin = fs.readFileSync(path.join(HERE, '../web/admin.html'), 'utf8');
  return '/* GENERATED by build/pages.mjs from web/*.html. Do not edit by hand. */\n'
    + 'export const PLAY_PAGE = ' + JSON.stringify(play) + ';\n'
    + 'export const ADMIN_PAGE = ' + JSON.stringify(admin) + ';\n';
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(path.join(HERE, '../pages.js'), render());
  console.log('wrote functions/_stumpire/pages.js');
}
