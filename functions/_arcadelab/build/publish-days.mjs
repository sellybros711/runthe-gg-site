#!/usr/bin/env node
/* Write a SQL file that approves Claude's drafted prompts and themes and
 * publishes a run of days for Whack the Right Player and Drop Board, for
 * when there is no editor yet to do it in the admin page. Every prompt and
 * theme is re-validated here, and a snapshot is built exactly as the admin
 * publish builds it. A day that already has a slate is left alone (the
 * insert does nothing on conflict, and the trigger refuses any change).
 *
 *   node functions/_arcadelab/build/publish-days.mjs <first date> <days> > supabase/NNN_x.sql
 *
 * Whack rounds go easiest first: an MVP prompt, then a mid prompt, then a
 * hard one, each list rotating on its own length so the trios do not repeat.
 * Drop Board walks every theme once, then every theme's next variant. */
import fs from 'node:fs';
import * as C from '../content/index.js';

C.setLookups(JSON.parse(fs.readFileSync(new URL('../../_stumpire/data/search_avg.json', import.meta.url), 'utf8')).values);
const args = process.argv.slice(2), ri = args.indexOf('--replace');
const replace = ri >= 0 ? args.splice(ri, 2)[1] : null;
const [first, n] = [args[0], +args[1] || 21];
if (!/^\d{4}-\d{2}-\d{2}$/.test(first || '') || (replace && !['whack', 'drop-board'].includes(replace))) { console.error('usage: publish-days.mjs YYYY-MM-DD [days] [--replace whack|drop-board]'); process.exit(1); }
const want = g => !replace || replace === g;
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const j = o => q(JSON.stringify(o)) + '::jsonb';

const W = C.whack, D = C.drop;
const whack = W.TEMPLATES.map(W.draftPrompt);
// every theme's first board, then every theme's second, so a theme comes round
// again with different athletes; a variant identical to an earlier one is dropped
const drop = [], seenBoards = new Set();
for (let v = 0; v < D.VARIANTS; v++) for (const t of D.STAT_THEMES) {
  const x = D.draftTheme(t, v), k = x.def.slots.map(s => s.id).join(',');
  if (!seenBoards.has(k)) { seenBoards.add(k); drop.push(x); }
}
for (const { def, report } of [...whack, ...drop]) if (!report.ok) { console.error(def.id + ' does not validate: ' + report.errors[0]); process.exit(1); }
const byTitle = t => whack.find(x => x.def.title === t).def;
const EASY = ['Hit every NBA MVP', 'Hit every MLB MVP', 'Hit every NFL MVP', 'Hit every Super Bowl MVP'].map(byTitle);
const MID = ['Hit every Cy Young winner', 'Hit every NBA Finals MVP', 'Hit every World Series MVP', 'Hit every NFL Defensive Player of the Year'].map(byTitle);
const HARD = ['Hit every Sixth Man of the Year', 'Hit every NBA Defensive Player of the Year', 'Hit every NFL Offensive Rookie of the Year'].map(byTitle);

const out = ['-- Generated by functions/_arcadelab/build/publish-days.mjs. Approves Claude\'s drafts and',
  '-- publishes ' + n + ' days from ' + first + ' for Whack the Right Player and Drop Board.',
  '-- Idempotent: a day already published is left alone; a prompt only Claude has drafted is refreshed.', ''];
if (replace) out.push('-- --replace ' + replace + ': a day nobody has played yet is taken down and published again.',
  '-- A day with a run on it keeps the slate it was scored against.',
  'alter table public.arcade_slates disable trigger arcade_slates_frozen;');
for (const { def, report } of want('whack') ? whack : []) out.push('insert into public.arcade_prompts (id, game_id, def, status, report, drafted_by) values (' +
  [q(def.id), q('whack'), j(def), q('approved'), j(report), q('claude')].join(', ') + ') on conflict (id) do update set def = excluded.def, status = excluded.status, report = excluded.report where arcade_prompts.drafted_by = ' + q('claude') + ';');
for (const { def, report } of want('drop-board') ? drop : []) out.push('insert into public.arcade_prompts (id, game_id, def, status, report, drafted_by) values (' +
  [q(def.id), q('drop-board'), j(def), q('approved'), j(report), q('claude')].join(', ') + ') on conflict (id) do update set def = excluded.def, status = excluded.status, report = excluded.report where arcade_prompts.drafted_by = ' + q('claude') + ';');
const day0 = Date.parse(first + 'T12:00:00Z');
for (let i = 0; i < n; i++) {
  const d = new Date(day0 + i * 86400000).toISOString().slice(0, 10);
  const trio = [EASY[i % EASY.length], MID[i % MID.length], HARD[i % HARD.length]];
  const theme = drop[i % drop.length].def;
  const take = g => { if (replace === g) out.push('delete from public.arcade_slates s where s.game_id = ' + q(g) + ' and s.date_key = ' + q(d) +
    ' and not exists (select 1 from public.arcade_runs r where r.game_id = s.game_id and r.date_key = s.date_key);'); };
  if (want('whack')) { take('whack'); out.push('insert into public.arcade_slates (game_id, date_key, payload, source_ids) values (' +
    [q('whack'), q(d), j(W.snapshotSlate(trio)), 'array[' + trio.map(t => q(t.id)).join(', ') + ']'].join(', ') + ') on conflict do nothing;'); }
  if (want('drop-board')) { take('drop-board'); out.push('insert into public.arcade_slates (game_id, date_key, payload, source_ids) values (' +
    [q('drop-board'), q(d), j(D.snapshotTheme(theme)), 'array[' + q(theme.id) + ']'].join(', ') + ') on conflict do nothing;'); }
}
if (replace) {
  const ids = (replace === 'whack' ? whack : drop).map(x => q(x.def.id)).join(', ');
  out.push('update public.arcade_prompts set status = ' + q('rejected') + ', updated_at = now() where game_id = ' + q(replace) +
    ' and drafted_by = ' + q('claude') + ' and id not in (' + ids + ');');
  out.push('alter table public.arcade_slates enable trigger arcade_slates_frozen;');
}
process.stdout.write(out.join('\n') + '\n');
