#!/usr/bin/env node
/* Build Last Shot's page and browser modules, stamped with one BUILD, in two
 * places that hold the same bytes:
 *
 *   last-shot/index.html      the page, served as a static file at /last-shot/
 *   last-shot/m/<name>.js     each browser module, static at /last-shot/m/
 *   functions/_lastshot/pages.js   the same strings as one bundle (BUILD, PAGE,
 *                             MODULES), for the tests and check-posture.mjs
 *
 * The static folder is what production serves (since 2026-11-19): a static
 * file costs no Function invocation, and a first visit is the page and 30
 * modules. Only POST /last-shot/e and GET /last-shot/report are Functions
 * (functions/last-shot/e.js and report.js).
 *
 * After editing web/play.html or any browser module:
 *
 *   node functions/_lastshot/build/pages.mjs
 *
 * test/gate.test.mjs and check-posture.mjs fail if pages.js or the folder has
 * drifted from the sources, or if the folder holds a file the build did not
 * write. Never edit last-shot/ by hand: the next build overwrites it. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const REPO = path.join(ROOT, '../..');
/* the static folder at the site root, served at /last-shot/ */
export const STATIC_DIR = path.join(REPO, 'last-shot');

/* What the browser may load. Server files (gate, db, pages) are not here. */
export const MODULE_FILES = ['scenario.js', 'starters.js', 'rng.js', 'court-geo.js', 'motion.js', 'defense.js', 'shot.js', 'playbook.js', 'names.js', 'book.js', 'testit.js', 'diagram.js', 'export.js', 'book-ui.js',
  'sim.js', 'levels.js', 'ladder-ui.js', 'daily.js', 'challenge.js', 'cards.js', 'daily-ui.js', 'beat-ui.js', 'view.js', 'board.js', 'court.js', 'share.js', 'sound.js', 'analytics.js', 'client.js', 'ads.js'];

export const stamp = (src, build) =>
  src.replace(/(\bfrom\s*|\bimport\s*\(\s*)(['"])(\.\/[A-Za-z0-9_-]+\.js)\2/g, (m, a, q, p) => a + q + p + '?b=' + build + q);

/* The page and the modules, stamped: { build, page, mods }. */
export function compile() {
  const mods = {};
  for (const f of MODULE_FILES) mods[f] = fs.readFileSync(path.join(ROOT, f), 'utf8');
  const build = crypto.createHash('sha256').update(JSON.stringify(mods)).digest('hex').slice(0, 10);
  /* Every relative import carries the build too (2026-11-16), so a browser
     may keep a module for a year (_headers): a new build is a new URL all the
     way down, never a stale sim under a fresh page. */
  for (const f of MODULE_FILES) mods[f] = stamp(mods[f], build);
  const page = fs.readFileSync(path.join(ROOT, 'web/play.html'), 'utf8').replaceAll('__BUILD__', build);
  return { build, page, mods };
}

/* pages.js, as text. */
export function render(c = compile()) {
  return '/* GENERATED by build/pages.mjs. Do not edit by hand. */\n'
    + 'export const BUILD = ' + JSON.stringify(c.build) + ';\n'
    + 'export const PAGE = ' + JSON.stringify(c.page) + ';\n'
    + 'export const MODULES = ' + JSON.stringify(c.mods) + ';\n';
}

/* The static folder, as { 'index.html': text, 'm/<name>.js': text }. */
export function staticFiles(c = compile()) {
  const out = { 'index.html': c.page };
  for (const f of MODULE_FILES) out['m/' + f] = c.mods[f];
  return out;
}

/* Every file under the static folder now, relative to it, posix slashes. */
export function listStatic(dir = STATIC_DIR) {
  const out = [];
  const walk = (d, rel) => {
    if (!fs.existsSync(d)) return;
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const r = rel ? rel + '/' + e.name : e.name;
      if (e.isDirectory()) walk(path.join(d, e.name), r); else out.push(r);
    }
  };
  walk(dir, '');
  return out.sort();
}

/* What is wrong with the folder against the sources, as sentences (none: in step). */
export function staticProblems(dir = STATIC_DIR, c = compile()) {
  const want = staticFiles(c), have = listStatic(dir), problems = [];
  for (const f of Object.keys(want)) {
    if (!have.includes(f)) problems.push('last-shot/' + f + ' is missing');
    else if (fs.readFileSync(path.join(dir, f), 'utf8') !== want[f]) problems.push('last-shot/' + f + ' is stale');
  }
  for (const f of have) if (!(f in want)) problems.push('last-shot/' + f + ' is not a file the build writes');
  return problems;
}

/* Write pages.js and the folder. A file whose bytes are already right is left
   alone, and a file the build does not write is removed. */
export function writeAll() {
  const c = compile();
  const put = (p, text) => { if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); } };
  put(path.join(ROOT, 'pages.js'), render(c));
  const want = staticFiles(c);
  for (const f of listStatic()) if (!(f in want)) fs.rmSync(path.join(STATIC_DIR, f));
  for (const [f, text] of Object.entries(want)) put(path.join(STATIC_DIR, f), text);
  return c;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const c = writeAll();
  console.log('wrote functions/_lastshot/pages.js and last-shot/ (index.html, ' + MODULE_FILES.length + ' modules), build ' + c.build);
}
