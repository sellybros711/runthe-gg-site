#!/usr/bin/env node
/* Write functions/_lastshot/pages.js: the page shell and every browser
 * module, as strings. They are served by functions/last-shot/[[path]].js
 * behind the tester gate, never as static files. After editing web/play.html
 * or any browser module:
 *
 *   node functions/_lastshot/build/pages.mjs
 *
 * test/gate.test.mjs fails if pages.js has drifted from the sources. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');

/* What the browser may load. Server files (gate, db, pages) are not here. */
export const MODULE_FILES = ['scenario.js', 'starters.js', 'rng.js', 'court-geo.js', 'motion.js', 'defense.js', 'shot.js', 'playbook.js', 'names.js', 'book.js', 'testit.js', 'diagram.js', 'export.js', 'book-ui.js',
  'sim.js', 'levels.js', 'ladder-ui.js', 'daily.js', 'challenge.js', 'cards.js', 'daily-ui.js', 'beat-ui.js', 'view.js', 'board.js', 'court2d.js', 'run-view.js', 'share.js', 'sound.js', 'analytics.js', 'client.js', 'ads.js'];

export const stamp = (src, build) =>
  src.replace(/(\bfrom\s*|\bimport\s*\(\s*)(['"])(\.\/[A-Za-z0-9_-]+\.js)\2/g, (m, a, q, p) => a + q + p + '?b=' + build + q);

export function render() {
  const mods = {};
  for (const f of MODULE_FILES) mods[f] = fs.readFileSync(path.join(ROOT, f), 'utf8');
  const build = crypto.createHash('sha256').update(JSON.stringify(mods)).digest('hex').slice(0, 10);
  /* Every relative import carries the build too (2026-11-16), so the server
     can let the browser keep a module for a year: a new build is a new URL
     all the way down, never a stale sim under a fresh page. */
  for (const f of MODULE_FILES) mods[f] = stamp(mods[f], build);
  const page = fs.readFileSync(path.join(ROOT, 'web/play.html'), 'utf8').replaceAll('__BUILD__', build);
  return '/* GENERATED by build/pages.mjs. Do not edit by hand. */\n'
    + 'export const BUILD = ' + JSON.stringify(build) + ';\n'
    + 'export const PAGE = ' + JSON.stringify(page) + ';\n'
    + 'export const MODULES = ' + JSON.stringify(mods) + ';\n';
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(path.join(ROOT, 'pages.js'), render());
  console.log('wrote functions/_lastshot/pages.js');
}
