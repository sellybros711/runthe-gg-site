#!/usr/bin/env node
/* Write functions/_skyworld/pages.js: the sign in screen and every browser module, as strings. They are
 * served by functions/skyworld/[[path]].js and never as static files. After editing web/:
 *
 *   node functions/_skyworld/build/pages.mjs
 *
 * test/discover.test.mjs fails if pages.js has drifted from web/, and test/gate.test.mjs serves every module
 * to a tester and refuses it to everyone else.
 *
 * MODULE_FILES is the one list of the world's browser modules. boot.js comes first and loads the rest, in this
 * order (each is a classic script on window.SKY_W, so the order matters): its LOAD is written from this list. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MODULE_FILES = ['boot.js', 'noise.js', 'landmarks.js', 'ui.js', 'status.js', 'layout.js', 'land.js', 'props.js', 'paint.js',
  'camera.js', 'input.js', 'world.js', 'agents.js', 'ideas.js'];
const LOAD = 'var LOAD = [];';
export function render(){
  const read = f => fs.readFileSync(path.join(ROOT, 'web', f), 'utf8');
  const mods = Object.fromEntries(MODULE_FILES.map(f => [f, read('m/' + f)]));
  if (!mods['boot.js'].includes(LOAD)) throw new Error('boot.js has lost its line ' + LOAD);
  mods['boot.js'] = mods['boot.js'].replace(LOAD, 'var LOAD = ' + JSON.stringify(MODULE_FILES.slice(1)) + ';');
  return '/* GENERATED by functions/_skyworld/build/pages.mjs from web/. Do not hand edit. */\n' +
    'export const SHELL = ' + JSON.stringify(read('shell.html')) + ';\n' +
    'export const MODULES = ' + JSON.stringify(mods, null, 0) + ';\n';
}
if (process.argv[1] === fileURLToPath(import.meta.url)) { fs.writeFileSync(path.join(ROOT, 'pages.js'), render()); console.log('pages.js written'); }
