/* Where does the SAFE target on an approach decision actually point?
 *
 *   (nohup python3 -m http.server 8099 &)
 *   node golf/verify-safe-target.mjs
 *
 * The option is labelled "Middle" and it is the one a player picks to avoid trouble, so it pointing INTO
 * a greenside bunker is worse than a cosmetic slip: the card beside it is at that moment quoting a bunker
 * percentage as the reason NOT to take the other line (owner: "why does middle look like its pointed in
 * the bunker").
 *
 * It used to be one step sideways, gcx plus 0.6 of the green's x-radius, away from the pin. Two things
 * were wrong with that and this measures both:
 *
 *   the pin only ever sits 0.42 to 0.58 of that radius out, so "Middle" was further off centre than the
 *   flag it was supposedly playing away from
 *   nothing read g.bunkers, which is in the same coordinates, so whatever was on that side was hit
 *
 * Every hole here is GENERATED by the shipped code, not stated: the same dHoleGeom() the tracer draws
 * from, across every daily course and all eighteen holes, with the pin rotation walked so each hole is
 * measured at all four of its real pin positions. The OLD rule is recomputed alongside the new one from
 * the same geometry, so the two columns are the same holes and the comparison means something.
 */
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const HOST = process.env.HOST || 'http://localhost:8099';
const SRC = ROOT + '/golf/index.html';
const PROBE = ROOT + '/golf/__test_safetgt.html';

let bad = 0;
const ok = (n, p, x) => { if (!p) bad++;
  console.log((p ? '  ok   ' : ' FAIL  ') + n + (x !== undefined ? '   ' + JSON.stringify(x).slice(0, 200) : '')); };
const head = (t) => console.log('\n' + t + '\n' + '-'.repeat(t.length));

const HOOK = `
window.__ST = {
  /* Walk every daily course, every hole, every pin. For each one take the approach decision's two
     targets and report how much room the safe point has. Clearance is distance to the nearest hazard
     EDGE, so a negative number means the point is inside it. */
  sweep(){
    var out=[], keys=Object.keys(DAILY_COURSES);
    // hvPinRot() reads S.dailySeed, so walking the seed walks the pin the way a new day does
    S.daily=true; S.h2h=null;
    for(var ci=0; ci<keys.length; ci++){
      var ck=keys[ci];
      var holes=(DAILY_COURSES[ck]||{}).holes||[];
      for(var h=0; h<holes.length; h++){
        for(var rot=0; rot<4; rot++){
          S.dailySeed=20260101+rot*37;
          var seedN=(dHash(ck||'x')^Math.imul((h|0)+1,0x9e3779b1))>>>0;
          var g;
          try{ g=hvGeom(seedN, holes[h][0], holes[h][1]||400, ck, h); }catch(e){ continue; }
          if(!g || !g.greenR) continue;
          var pin=g.pin||[g.gcx,g.L];
          // the approach scenario the two chips are placed for
          var sc={phase:'approach', tag:'Approach', prompt:'60 yds to the green', clubs:{}};
          var tg=dDecTargets(g, sc);
          /* Room to the nearest SAND. Bunkers are what the player sees the ring sitting on, and they are
             drawn as circles off the green, so distance to the edge is the honest measure. Water is
             measured separately below and cannot use the same shape: a pond is an ELLIPSE, and on an
             island green it is drawn wrapping the whole putting surface, so treating it as a circle of
             its longer radius reports the middle of an island green as eighteen yards under water. It is
             not. The green is grass. */
          var sandClear=function(x,y){
            var c=999;
            (g.bunkers||[]).forEach(function(b){ c=Math.min(c, Math.hypot(x-b.x,y-b.y)-b.r); });
            return c; };
          var onGreen=function(x,y){
            return (Math.pow((x-g.gcx)/g.greenR[0],2)+Math.pow((y-g.L)/g.greenR[1],2))<=1; };
          /* the most room any point on one side of the green's centre line can get, over the same grid the
             shipped code searches. Lets the check ask WHY a target crossed rather than counting how often. */
          var bestSideRoom=function(sgn){
            var b=-999;
            for(var ix=0; ix<=3; ix++) for(var iy=-2; iy<=2; iy++){
              var x=g.gcx+sgn*ix*g.greenR[0]*0.17, y=g.L+iy*g.greenR[1]*0.17;
              b=Math.max(b, sandClear(x,y));
            }
            return b; };
          var minRoom=function(){
            var m=999;
            for(var ix=-3; ix<=3; ix++) for(var iy=-2; iy<=2; iy++)
              m=Math.min(m, sandClear(g.gcx+ix*g.greenR[0]*0.17, g.L+iy*g.greenR[1]*0.17));
            return m; };
          var inWater=function(x,y){
            if(!g.water || onGreen(x,y)) return false;
            return (Math.pow((x-g.water.x)/g.water.rx,2)+Math.pow((y-g.water.y)/g.water.ry,2))<=1; };
          // the rule this replaced, recomputed from the SAME geometry so the columns compare
          var oldOff=Math.max(3,(g.greenR?g.greenR[0]:12)*0.6)*(pin[0]>g.gcx?-1:1);
          var oldPt=[g.gcx+oldOff, g.L];
          out.push({
            course:ck, hole:h, rot:rot,
            rx:g.greenR[0], ry:g.greenR[1], nbunk:(g.bunkers||[]).length, water:!!g.water,
            newClear:+sandClear(tg.safe[0],tg.safe[1]).toFixed(2),
            oldClear:+sandClear(oldPt[0],oldPt[1]).toFixed(2),
            newWet:inWater(tg.safe[0],tg.safe[1]), oldWet:inWater(oldPt[0],oldPt[1]),
            island:!!g.island,
            // how far off the green's centre each one sits, as a fraction of the radius
            newOff:+(Math.abs(tg.safe[0]-g.gcx)/g.greenR[0]).toFixed(3),
            oldOff:+(Math.abs(oldPt[0]-g.gcx)/g.greenR[0]).toFixed(3),
            pinOff:+(Math.abs(pin[0]-g.gcx)/g.greenR[0]).toFixed(3),
            // is the safe point still on the side away from the pin? and when it is not, was that side
            // actually the tighter one? (best room available on each side of the green's centre line)
            awaySide:((tg.safe[0]-g.gcx)*(pin[0]-g.gcx)<=0),
            bestAway:+bestSideRoom(pin[0]>g.gcx?-1:1).toFixed(2),
            bestPinSide:+bestSideRoom(pin[0]>g.gcx?1:-1).toFixed(2),
            // the LEAST room any candidate point has. High means there is nothing to avoid anywhere on
            // this green, which is the only state where the side preference should decide alone.
            minRoomAll:+minRoom().toFixed(2),
            // and still inside the green?
            onGreen:(Math.pow((tg.safe[0]-g.gcx)/g.greenR[0],2)+Math.pow((tg.safe[1]-g.L)/g.greenR[1],2))<=1,
            sl:tg.sl, al:tg.al
          });
        }
      }
    }
    return out;
  },
  courses(){ return Object.keys(DAILY_COURSES).length; }
};
`;

function buildProbe() {
  const src = fs.readFileSync(SRC, 'utf8');
  const re = /<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g;
  let m, best = null;
  while ((m = re.exec(src))) { if (!best || m[1].length > best[1].length) best = m; }
  if (!best) throw new Error('no inline script found in golf/index.html');
  const at = best.index + best[0].length - '</script>'.length;
  fs.writeFileSync(PROBE, src.slice(0, at) + '\n' + HOOK + '\n' + src.slice(at));
}

const pct = (n, d) => (100 * n / d).toFixed(1) + '%';

const run = async () => {
  buildProbe();
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await page.addInitScript(() => { try { localStorage.setItem('bag_tour_done', 'true'); } catch (e) {} });
  await page.goto(HOST + '/golf/__test_safetgt.html', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction('!!window.__ST', null, { timeout: 20000 });

  const nCourses = await page.evaluate(() => window.__ST.courses());
  const rows = await page.evaluate(() => window.__ST.sweep());

  head('the sample');
  console.log(`    ${nCourses} daily courses x 18 holes x 4 pin positions = ${rows.length} approach decisions`);
  ok('every one of them produced a target', rows.length >= nCourses * 18 * 4 - 4, rows.length);
  ok('and they are all still labelled Middle vs At the pin',
    rows.every(r => r.sl === 'Middle' && r.al === 'At the pin'));

  const withSand = rows.filter(r => r.nbunk > 0 || r.water);

  /* WHAT "POINTED IN THE BUNKER" ACTUALLY MEANS, and getting this wrong once is worth writing down.
     The first version of this check asked whether the aim point was strictly INSIDE a bunker, and the
     answer for the old rule was never, on any of the 4032. That reading would have closed the report as
     a phantom, and the screenshot is not a phantom. The ring is a drawn shape with a radius of its own,
     so a point a yard and a half from the sand IS a ring sitting on the sand. The measure that matches
     what a player sees is the gap, not the overlap. */
  const TIGHT = 6;   // about the drawn radius of the safe ring in course units
  const oldIn = rows.filter(r => r.oldClear < TIGHT);
  const newIn = rows.filter(r => r.newClear < TIGHT);

  head('does the safe option sit on a bunker');
  console.log(`    holes with sand or water near the green: ${withSand.length} of ${rows.length}`);
  console.log(`    OLD rule, safe point within ${TIGHT} of sand: ${oldIn.length}  (${pct(oldIn.length, rows.length)})`);
  console.log(`    NEW rule, safe point within ${TIGHT} of sand: ${newIn.length}  (${pct(newIn.length, rows.length)})`);
  console.log(`    strictly inside a bunker: old ${rows.filter(r => r.oldClear < 0).length}, new ${rows.filter(r => r.newClear < 0).length}`);
  ok('the old rule really did put the ring on the sand, so this is not a phantom', oldIn.length > 0, oldIn.length);
  ok('and it is far rarer now', newIn.length < oldIn.length / 3, { old: oldIn.length, now: newIn.length });
  ok('neither rule ever aimed strictly inside a bunker, which is why reading the code beat guessing',
    rows.every(r => r.newClear >= 0));
  ok('and the new one is never in water', rows.filter(r => r.newWet).length === 0,
    rows.filter(r => r.newWet).slice(0, 2));
  console.log(`    (${rows.filter(r => r.island).length} island greens in here, where the pond wraps the putting`);
  console.log(`     surface: a point ON the green is grass, which is why water is an ellipse test against`);
  console.log(`     the green rather than a radius. Measuring it as a circle reported the middle of an`);
  console.log(`     island green as eighteen yards under water.)`);

  const worseCount = rows.filter(r => r.newClear < r.oldClear - 0.01).length;
  const betterCount = rows.filter(r => r.newClear > r.oldClear + 0.01).length;
  head('room around the safe point');
  const mean = (a, k) => (a.reduce((s, r) => s + r[k], 0) / a.length).toFixed(2);
  const worst = (a, k) => Math.min(...a.map(r => r[k])).toFixed(2);
  console.log(`    mean room to the nearest sand   old ${mean(rows, 'oldClear')}  ->  new ${mean(rows, 'newClear')}`);
  console.log(`    worst hole on the whole site    old ${worst(rows, 'oldClear')}  ->  new ${worst(rows, 'newClear')}`);
  console.log(`    more room on ${betterCount} holes, less on ${worseCount}`);
  ok('the average safe point has more room than it used to', +mean(rows, 'newClear') > +mean(rows, 'oldClear'));
  ok('and so does the worst one, which is the hole somebody screenshots',
    +worst(rows, 'newClear') > +worst(rows, 'oldClear'), { old: worst(rows, 'oldClear'), now: worst(rows, 'newClear') });

  head('it is called Middle, so it has to be near the middle');
  const om = (rows.reduce((s, r) => s + r.oldOff, 0) / rows.length).toFixed(3);
  const nm = (rows.reduce((s, r) => s + r.newOff, 0) / rows.length).toFixed(3);
  const pm = (rows.reduce((s, r) => s + r.pinOff, 0) / rows.length).toFixed(3);
  console.log(`    distance off the green's centre, as a fraction of its radius:`);
  console.log(`      the pin  ${pm}      old "Middle"  ${om}      new "Middle"  ${nm}`);
  ok('the old rule put Middle FURTHER out than the pin, which is the label being false', +om > +pm, { old: om, pin: pm });
  ok('the new one is nearer the centre than the pin is', +nm < +pm, { now: nm, pin: pm });
  ok('and never past 0.53 of the radius, so it stays the fat of the green',
    rows.every(r => r.newOff <= 0.531), rows.filter(r => r.newOff > 0.531).slice(0, 2));
  ok('every safe point is on the green', rows.every(r => r.onGreen),
    rows.filter(r => !r.onGreen).slice(0, 2));

  head('it is still the shot away from the flag, unless that is where the sand is');
  const away = rows.filter(r => r.awaySide).length;
  const notAway = rows.filter(r => !r.awaySide);
  console.log(`    on the side away from the pin: ${pct(away, rows.length)}`);
  console.log(`    crossed to the pin's side: ${notAway.length}`);
  ok('it is the away side on most holes', away / rows.length > 0.8, pct(away, rows.length));
  /* A percentage on its own proves nothing, since it can be tuned to any number. The check that catches
     an ARBITRARY crossing is this one: on a green with no sand anywhere near it there is nothing for the
     clearance term to weigh, so the side preference has to be what decides, every time. If those holes
     ever crossed, the target would be wandering for no reason a player could see.
     Holes that DO have sand are reported rather than asserted: the card captions this option "Play to
     the open side", and when the side away from the pin is the side holding the bunker, the open side is
     the other one. Pinning that down with a threshold would be inventing a rule to pass a test. */
  // "Nothing to avoid" has to mean no candidate anywhere on the green is near sand, not merely that each
  // side holds one clean spot. The looser reading was tried first and reported 21 arbitrary crossings that
  // were not arbitrary at all: those greens had a bunker biting into the away side between its clean spots.
  const clean = rows.filter(r => r.minRoomAll >= 16);
  console.log(`    greens with nothing to avoid anywhere: ${clean.length}`);
  ok('and on one of those, it is ALWAYS the side away from the flag',
    clean.every(r => r.awaySide), clean.filter(r => !r.awaySide).slice(0, 3)
      .map(r => ({ course: r.course, hole: r.hole, minRoom: r.minRoomAll })));
  console.log(`    every crossing happens on a green with sand in play: ${notAway.every(r => r.minRoomAll < 16)}`);
  ok('so no target ever wanders for a reason a player could not see',
    notAway.every(r => r.minRoomAll < 16));

  head('page errors');
  ok('none', errs.length === 0, errs.slice(0, 3));
  await browser.close();
};

try { await run(); } finally { try { fs.unlinkSync(PROBE); } catch (e) {} }
console.log('\n' + (bad ? bad + ' FAILED' : 'all good'));
process.exit(bad ? 1 : 0);
