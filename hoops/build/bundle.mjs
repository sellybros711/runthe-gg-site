/*
 * Run The Floor: build the game's two big scripts from their parts.
 *
 *   node hoops/build/bundle.mjs           write hoops/career.js and hoops/page.js
 *   node hoops/build/bundle.mjs --check   fail if either is not its parts
 *
 *   hoops/career/  ->  hoops/career.js   the Career engine (window.RTF_CAREER, node require)
 *   hoops/page/    ->  hoops/page.js     the page: the draft game, the bracket, the boards,
 *                                        the shelf and the wiring (window.RTF_PAGE and friends)
 *
 * Each is ONE closure, the way each was always one file (page.js was the inline script in
 * index.html until 2026-10-16), so a name in one part is read in any other with no import and
 * no prefix. The page and every check load the one built file, with its one ?v=, which is why
 * this is a join and not a module system. The parts are the source. A part is plain
 * declarations in the closure's order: a constant a later part reads at load time has to be in
 * an earlier part, the same rule as reading it further down one file.
 *
 * After editing a part: run this, bump the built file's ?v= in hoops/index.html, then
 * node scripts/check-cachebust.mjs --update. hoops-checks runs --check.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HOOPS = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

const BUNDLES = [
  {
    name: 'career',
    /* The order is the closure's order. Every file in the folder is listed, and a file
       nobody listed fails, so a new part cannot be left out of the build. */
    parts: [
      'about',         // what Career is, and the shape of a year (comments only)
      'tuning',        // every balance number, first so any part may read one at load
      'basics',        // the league's clubs list, the player: positions, ratings, archetypes, sizes; small helpers
      'league',        // club strength, name pools, the coaching carousel, the rosters, the front office
      'people',        // who a line is about: the locker room, the tokens, say()
      'comps',         // the real players you are set beside: shades, a season's twin, the men you pass
      'life',          // a new life, the save and how an old one is brought forward
      'season',        // draft night, a season, the awards, the playoffs and moments, the offseason, the legacy
      'events',        // the NBA event catalog, the press room, the people around you, milestones
      'club',          // the bench and your role, the trade deadline, the summer
      'story-engine',  // the event schema, the narrator, continuity, memory and arcs, traits, the living league
      'amateur',       // high school and college, and their cards
      'story',         // the Phase D compiler, your club's cards, origins, routes, endings
      'stories',       // the authored storylines and epilogues: content only
      'turns',         // answering a card, the step machine, things to do between cards
      'moves',         // your moves: the trade ask, the holdout, the supermax, the shoe, the body, the podcast
      'api',           // what the page reads, the generated road, a son, the public object
    ],
    head: "'use strict';\n(function() {\n\n",
    tail: '})();\n',
  },
  {
    name: 'page',
    parts: [
      'boot',      // the modules the page reads, their version pins and stubs, small helpers, the crash banner
      'shell',     // the dock and the app bar, and loading the data
      'draft',     // a draft run: starting one, the club picker, the box score viewer, the first visit guide
      'reels',     // the loading bar, the connection rail, the ring, position pills, the going rate, the reels
      'court',     // the court, the arenas and the camera, the jersey, the profile, the Locker
      'front',     // the front page playing itself
      'hud',       // the pinned HUD, the draft board and its tiles, signing a man
      'season',    // playing the season
      'bracket',   // the playoff bracket and the live game seven (window.RTF_LIVE)
      'results',   // the result, the board submit, the board screen, the season story
      'share',     // the share text and the share card
      'records',   // the draft game's record on this device: runs, bests, badges, the cabinet
      'home',      // the home page's doors
      'sync',      // saving and restoring, and the shelf (cloud saves, window.RTF_SYNC)
      'wiring',    // the buttons, the feats, window.RTF_PAGE, and boot()
    ],
    head: "(function(){\n'use strict';\n\n",
    tail: '})();\n',
  },
];

const banner = (b) => `/* GENERATED: do not edit this file. It is built from the parts in
 * hoops/${b.name}/ by \`node hoops/build/bundle.mjs\`. Edit a part, run
 * that, then bump ${b.name}.js?v= in hoops/index.html. hoops-checks fails when
 * this file and its parts disagree.
 */
`;

let bad = 0;
for (const b of BUNDLES) {
  const dir = path.join(HOOPS, b.name), out = path.join(HOOPS, b.name + '.js');
  const onDisk = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).map((f) => f.slice(0, -3)).sort();
  const unlisted = onDisk.filter((f) => !b.parts.includes(f));
  const missing = b.parts.filter((f) => !onDisk.includes(f));
  if (unlisted.length || missing.length) {
    console.error(`hoops/${b.name}/ and the part list disagree: ` +
      (unlisted.length ? 'not listed ' + unlisted.join(', ') + '. ' : '') +
      (missing.length ? 'missing ' + missing.join(', ') + '.' : ''));
    bad++;
    continue;
  }
  const built = banner(b) + b.head + b.parts.map((p) => fs.readFileSync(path.join(dir, p + '.js'), 'utf8').replace(/\n*$/, '\n')).join('\n') + b.tail;
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (now !== built) {
      console.error(`hoops/${b.name}.js is not its parts. Edit hoops/${b.name}/, never ${b.name}.js, then run:\n` +
        '  node hoops/build/bundle.mjs');
      bad++;
    } else console.log(`${b.name}.js is its ${b.parts.length} parts`);
  } else {
    fs.writeFileSync(out, built);
    console.log(`wrote hoops/${b.name}.js from ${b.parts.length} parts (${built.split('\n').length} lines)`);
  }
}
if (bad) process.exit(1);
